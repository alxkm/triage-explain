"""Summarises the experiments of article 2.b into results/summary.md, and writes the audit sheet.

X1  explanations: share accepted by the grounding rules, which rule rejected the rest, length, latency, and
    specificity (an accepted explanation quotes at least one number from the detectors' evidence).
X2  the model as attributor: accuracy against the injected truth, from the evidence and from the readings, next to
    the detectors' accuracy on the same incidents.
X3  the explainer under provider failure: every explanation must fall back to the template within the budget.
"""
import csv
import json
import random
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
NUM = re.compile(r"(?<![\w.])-?\d+(?:\.\d+)?")
incidents = {}
for line in (R / "incidents.jsonl").read_text(encoding="utf-8").splitlines():
    if line.strip():
        d = json.loads(line.replace(":null", ":NaN").replace(",null", ",NaN").replace("[null", "[NaN"))
        incidents[d["id"]] = d


def q(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(p * len(xs)))] if xs else float("nan")


def evidence_numbers(i):
    return [float(x) for e in i["evidence"] for x in NUM.findall(e)]


def specific(text, i):
    allowed = evidence_numbers(i)
    for tok in NUM.findall(text):
        dec = len(tok.split(".")[1]) if "." in tok else 0
        if any(abs(float(tok) - a) <= 0.5 * 10 ** -dec + 1e-9 for a in allowed):
            return True
    return False


md = ["# Summary", "", "Generated by `scripts/summarize.py`.", ""]

# ---------------------------------------------------------------- X1
x1 = list(csv.DictReader(open(R / "X1_explanations.csv", encoding="utf-8")))
by = defaultdict(list)
for r in x1:
    by[r["port"]].append(r)
md += ["## X1 — explanations", "", "| Port | n | Accepted | R1 format | R2 cause | R3 number | R4 next check | R5 contradiction | R6 length | "
       "R0 call failed | Specific (of accepted) | Words, median | Latency median / P95 (ms) | Accepted when the decision was wrong |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for port, g in by.items():
    acc = [r for r in g if r["source"] == "model"]
    first = Counter(r["rejected"].split()[0].split(":")[0] for r in g if r["source"] != "model" and r["rejected"])
    spec = sum(specific(r["final_text"], incidents[r["id"]]) for r in acc)
    wrong = [r for r in g if r["cause"] != r["truth"]]
    md.append(f"| {port} | {len(g)} | {len(acc)} ({100 * len(acc) / len(g):.1f} %) | " + " | ".join(
        str(first.get(k, 0)) for k in ["R1-format", "R2-cause", "R3-number", "R4-next-check", "R5-contradiction", "R6-length", "R0-call"])
        + f" | {spec} ({100 * spec / max(1, len(acc)):.1f} %) | {statistics.median(int(r['words']) for r in acc) if acc else '-'} | "
        f"{statistics.median(int(r['millis']) for r in g):.0f} / {q([int(r['millis']) for r in g], 0.95)} | "
        f"{sum(r['source'] == 'model' for r in wrong)} of {len(wrong)} |")
md += ["", "Rule columns count the *first* failed rule of each rejected reply. *Specific*: the accepted text quotes a number "
       "from the evidence lines. *When the decision was wrong*: incidents whose decided cause differs from the injected one; "
       "an accepted explanation there states the decided (wrong) cause, as R2 requires.", ""]

# ---------------------------------------------------------------- X2
p2 = R / "X2_attribution.csv"
if p2.exists():
    x2 = list(csv.DictReader(open(p2, encoding="utf-8")))
    ids = sorted({r["id"] for r in x2})
    det = sum(incidents[i]["cause"] == incidents[i]["truth"] for i in ids)
    md += ["## X2 — the model as attributor", "", f"Detectors on the same {len(ids)} incidents: **{det} correct "
           f"({100 * det / len(ids):.1f} %)**.", "", "| Port | Input | n | Correct | No answer | Agrees with the detectors |", "|---|---|---|---|---|---|"]
    cells = defaultdict(list)
    for r in x2:
        cells[(r["port"], r["input"])].append(r)
    for (port, inp), g in sorted(cells.items()):
        ok = sum(r["model_cause"] == r["truth"] for r in g)
        none = sum(r["model_cause"] == "NONE" for r in g)
        agree = sum(r["model_cause"] == r["decided"] for r in g)
        md.append(f"| {port} | {inp} | {len(g)} | {ok} ({100 * ok / len(g):.1f} %) | {none} | {agree} ({100 * agree / len(g):.1f} %) |")
    md += ["", "Per true cause (correct / incidents):", "", "| Port | Input | " + " | ".join(["PROCESS", "INSTRUMENT", "DATA_PATH"]) + " |", "|---|---|---|---|---|"]
    for (port, inp), g in sorted(cells.items()):
        row = []
        for c in ["PROCESS", "INSTRUMENT", "DATA_PATH"]:
            gg = [r for r in g if r["truth"] == c]
            row.append(f"{sum(r['model_cause'] == c for r in gg)}/{len(gg)}")
        md.append(f"| {port} | {inp} | " + " | ".join(row) + " |")
    row = []
    for c in ["PROCESS", "INSTRUMENT", "DATA_PATH"]:
        gg = [i for i in ids if incidents[i]["truth"] == c]
        row.append(f"{sum(incidents[i]['cause'] == c for i in gg)}/{len(gg)}")
    md.append("| detectors | — | " + " | ".join(row) + " |")
    md.append("")

# ---------------------------------------------------------------- X3
p3 = R / "X3_failures.csv"
if p3.exists():
    x3 = list(csv.DictReader(open(p3, encoding="utf-8")))
    md += ["## X3 — provider failures", "", "| Port | Scenario | n | Template | Max time (ms) | Attempts |", "|---|---|---|---|---|---|"]
    cells = defaultdict(list)
    for r in x3:
        cells[(r["port"], r["scenario"])].append(r)
    for (port, sc), g in cells.items():
        md.append(f"| {port} | {sc} | {len(g)} | {sum(r['source'] == 'template' for r in g)} | {max(int(r['millis']) for r in g)} | "
                  f"{'/'.join(sorted({r['attempts'] for r in g}))} |")
    md.append("")

(R / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))

# ---------------------------------------------------------------- audit sheet (written once; the author fills it in)
sheet = R / "audit_sheet.csv"
if not sheet.exists() or "--new-audit" in sys.argv:
    rnd = random.Random(20261006)
    rows = []
    for port, g in sorted(by.items()):
        acc = [r for r in g if r["source"] == "model"]
        rows += rnd.sample(acc, min(10, len(acc)))
    with open(sheet, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["port", "id", "decided_cause", "evidence", "explanation", "faithful (y/n)", "unsupported claim (y/n)", "note"])
        for r in rows:
            w.writerow([r["port"], r["id"], r["cause"], " | ".join(incidents[r["id"]]["evidence"]), r["final_text"], "", "", ""])
